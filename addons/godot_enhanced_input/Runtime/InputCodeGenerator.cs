using System;
using System.Collections.Generic;
using System.Text;
using Godot;

namespace GodotEnhancedInput;

/// <summary>
/// Writes a strongly typed C# class for an <see cref="EnhancedInputConfig"/>, so game code names actions and
/// mapping contexts as members instead of strings or hand-assigned resources:
/// <code>
/// var input = GameInput.Shared;
/// if (input.Gameplay.Jump.WasPressed()) Jump();
/// var move = input.Gameplay.Move.ReadVector2();
/// using var driving = input.Vehicle.Push();
/// </code>
/// The class has one property per action and one nested class per mapping context (with that context's
/// actions). Members are resolved by stable id when the class is created, so renaming a display name does
/// not break code; renaming an id keeps working through its former ids. Regenerate after adding, removing
/// or renaming actions or mapping contexts (the config's Inspector and the Enhanced Input dock have a
/// button). The output is deterministic, so it diffs cleanly in version control.
/// </summary>
public static class InputCodeGenerator
{
    /// <summary>The first line of every generated file (generated files are recognized by it and may be overwritten).</summary>
    public const string Marker = "// <auto-generated> by Godot Enhanced Input";

    /// <summary>The class name used for a config: its name (or file name) in PascalCase, ending in "Input".</summary>
    public static string ClassNameFor(EnhancedInputConfig config, string path = null)
    {
        var baseName = !string.IsNullOrWhiteSpace(config?.Name) ? config.Name
            : !string.IsNullOrEmpty(path) ? path.GetFile().GetBaseName()
            : !string.IsNullOrEmpty(config?.ResourcePath) ? config.ResourcePath.GetFile().GetBaseName()
            : "Game";
        var name = Identifier(baseName);
        return name.EndsWith("Input", StringComparison.Ordinal) ? name : name + "Input";
    }

    /// <summary>A C# identifier in PascalCase for a name: "move_left" → MoveLeft, "2d look" → _2dLook.</summary>
    public static string Identifier(string text)
    {
        var sb = new StringBuilder();
        bool upper = true;
        foreach (char c in text ?? string.Empty)
        {
            if (char.IsLetterOrDigit(c))
            {
                sb.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }
            else upper = true;
        }
        if (sb.Length == 0) return "Unnamed";
        if (char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

    /// <summary>
    /// The source of the class for a config. <paramref name="configPath"/> is where the generated class
    /// loads the config from (the config's own path by default); <paramref name="namespace"/> may be empty.
    /// </summary>
    public static string Generate(EnhancedInputConfig config, string className = null, string @namespace = null, string configPath = null)
    {
        if (config == null) throw new ArgumentNullException(nameof(config));
        configPath ??= config.ResourcePath ?? string.Empty;
        className ??= ClassNameFor(config, configPath);

        // Mapping contexts and their actions, in the config's order; every action once at the top level.
        var contexts = new List<EnhancedInputMappingContext>();
        foreach (var list in new[] { config.Contexts, config.StartupContexts })
            foreach (var context in list)
                if (context != null && !contexts.Contains(context)) contexts.Add(context);
        var actions = new List<EnhancedInputAction>();
        foreach (var action in config.Actions)
            if (action != null && !actions.Contains(action)) actions.Add(action);
        var contextActions = new List<List<EnhancedInputAction>>();
        foreach (var context in contexts)
        {
            var own = new List<EnhancedInputAction>();
            foreach (var binding in context.Bindings)
            {
                var action = binding?.Action;
                if (action == null) continue;
                if (!own.Contains(action)) own.Add(action);
                if (!actions.Contains(action)) actions.Add(action);
            }
            contextActions.Add(own);
        }

        var top = new Names("Config", "ConfigPath", "Shared", className, "Resolve", "ResolveContext");
        var actionNames = new Dictionary<EnhancedInputAction, string>();
        foreach (var action in actions) actionNames[action] = top.Take(Identifier(action.Name));
        var contextNames = new List<(string Property, string Type)>();
        foreach (var context in contexts)
        {
            var property = top.Take(Identifier(context.Name));
            var type = top.Take(property + "Context");
            contextNames.Add((property, type));
        }

        var w = new Writer();
        w.Line(Marker + " from " + (string.IsNullOrEmpty(configPath) ? "a config" : configPath) + ".");
        w.Line("// Regenerate it after adding, removing or renaming actions or mapping contexts. Do not edit by hand.");
        w.Line("// </auto-generated>");
        w.Line("#nullable disable");
        w.Line("using Godot;");
        w.Line("using GodotEnhancedInput;");
        w.Line();
        if (!string.IsNullOrWhiteSpace(@namespace))
        {
            w.Line($"namespace {@namespace};");
            w.Line();
        }

        w.Line($"/// <summary>Typed access to the actions and mapping contexts of the input config {Doc(config.ToString())}.</summary>");
        w.Line($"public sealed partial class {className}");
        w.Open();
        w.Line("/// <summary>Where the config this class was generated from is.</summary>");
        w.Line($"public const string ConfigPath = {Literal(configPath)};");
        w.Line();
        w.Line($"private static {className} _shared;");
        w.Line();
        w.Line("/// <summary>One instance for the whole game, loaded from <see cref=\"ConfigPath\"/> on first use.</summary>");
        w.Line($"public static {className} Shared => _shared ??= new {className}();");
        w.Line();
        w.Line("/// <summary>The config the members were resolved from.</summary>");
        w.Line("public EnhancedInputConfig Config { get; }");
        foreach (var action in actions)
        {
            w.Line();
            w.Line($"/// <summary>The action {Doc(action.Name)} ({action.ValueKind}).</summary>");
            w.Line($"public EnhancedInputAction {actionNames[action]} {{ get; }}");
        }
        for (int i = 0; i < contexts.Count; i++)
        {
            w.Line();
            w.Line($"/// <summary>The mapping context {Doc(contexts[i].Name)} and its actions.</summary>");
            w.Line($"public {contextNames[i].Type} {contextNames[i].Property} {{ get; }}");
        }
        w.Line();
        w.Line("/// <summary>Loads the config from <see cref=\"ConfigPath\"/>.</summary>");
        w.Line($"public {className}() : this(ResourceLoader.Load<EnhancedInputConfig>(ConfigPath)) {{ }}");
        w.Line();
        w.Line("/// <summary>Resolves the members from a loaded config (one with the same ids, e.g. a modded copy).</summary>");
        w.Line($"public {className}(EnhancedInputConfig config)");
        w.Open();
        w.Line("Config = config;");
        foreach (var action in actions) w.Line($"{actionNames[action]} = Resolve(config, {Literal(action.Id)});");
        for (int i = 0; i < contexts.Count; i++) w.Line($"{contextNames[i].Property} = new {contextNames[i].Type}(config);");
        w.Close();
        w.Line();
        w.Line("private static EnhancedInputAction Resolve(EnhancedInputConfig config, string id)");
        w.Open();
        w.Line("var action = config?.FindAction(id);");
        w.Line($"if (action == null) GD.PushError($\"{className}: no action '{{id}}' in {{config?.ResourcePath ?? \"the config\"}}; regenerate the class.\");");
        w.Line("return action;");
        w.Close();
        w.Line();
        w.Line("private static EnhancedInputMappingContext ResolveContext(EnhancedInputConfig config, string id)");
        w.Open();
        w.Line("var context = config?.FindContext(id);");
        w.Line($"if (context == null) GD.PushError($\"{className}: no mapping context '{{id}}' in {{config?.ResourcePath ?? \"the config\"}}; regenerate the class.\");");
        w.Line("return context;");
        w.Close();

        for (int i = 0; i < contexts.Count; i++)
        {
            var context = contexts[i];
            var (_, type) = contextNames[i];
            var inner = new Names("Context", "Push", "Activate", "Deactivate", type);
            var names = new List<(EnhancedInputAction Action, string Name)>();
            foreach (var action in contextActions[i]) names.Add((action, inner.Take(Identifier(action.Name))));

            w.Line();
            w.Line($"/// <summary>The mapping context {Doc(context.Name)} and the actions it maps.</summary>");
            w.Line($"public sealed partial class {type}");
            w.Open();
            w.Line("/// <summary>The mapping context.</summary>");
            w.Line("public EnhancedInputMappingContext Context { get; }");
            foreach (var (action, name) in names)
            {
                w.Line();
                w.Line($"/// <summary>The action {Doc(action.Name)} ({action.ValueKind}).</summary>");
                w.Line($"public EnhancedInputAction {name} {{ get; }}");
            }
            w.Line();
            w.Line($"internal {type}(EnhancedInputConfig config)");
            w.Open();
            w.Line($"Context = ResolveContext(config, {Literal(context.Id)});");
            foreach (var (action, name) in names) w.Line($"{name} = Resolve(config, {Literal(action.Id)});");
            w.Close();
            w.Line();
            w.Line("/// <summary>Activates the mapping context on a player (the default player when null) until the handle is disposed.</summary>");
            w.Line("public ContextHandle Push(InputPlayer player = null, int? priority = null)");
            w.Line("    => (player ?? EnhancedInput.DefaultPlayer)?.PushContext(Context, priority ?? Context.DefaultPriority);");
            w.Line();
            w.Line("/// <summary>Activates the mapping context on a player (the default player when null) until it is deactivated.</summary>");
            w.Line("public void Activate(InputPlayer player = null, int? priority = null)");
            w.Line("    => (player ?? EnhancedInput.DefaultPlayer)?.AddContext(Context, priority ?? Context.DefaultPriority);");
            w.Line();
            w.Line("/// <summary>Deactivates the mapping context on a player (the default player when null).</summary>");
            w.Line("public bool Deactivate(InputPlayer player = null) => (player ?? EnhancedInput.DefaultPlayer)?.RemoveContext(Context) ?? false;");
            w.Close();
        }
        w.Close();
        return w.ToString();
    }

    private static string Literal(string text)
    {
        var sb = new StringBuilder("\"");
        foreach (char c in text ?? string.Empty)
        {
            switch (c)
            {
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default: sb.Append(c); break;
            }
        }
        return sb.Append('"').ToString();
    }

    private static string Doc(string text)
        => "<c>" + (text ?? string.Empty).Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ") + "</c>";

    /// <summary>Unique member names within one class.</summary>
    private sealed class Names
    {
        private readonly HashSet<string> _taken = new(StringComparer.Ordinal);

        public Names(params string[] reserved)
        {
            foreach (var name in reserved) _taken.Add(name);
        }

        public string Take(string wanted)
        {
            var name = wanted;
            for (int n = 2; !_taken.Add(name); n++) name = wanted + n;
            return name;
        }
    }

    private sealed class Writer
    {
        private readonly StringBuilder _sb = new();
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0) _sb.Append(' ', _indent * 4).Append(text);
            _sb.Append('\n');
        }

        public void Open()
        {
            Line("{");
            _indent++;
        }

        public void Close()
        {
            _indent--;
            Line("}");
        }

        public override string ToString() => _sb.ToString();
    }
}
